#!/usr/bin/env python3
"""Translate the Pseudoscalar_2HDMI UFO (parameters.py + decays.py) into a C++ header with the 2-body partial
widths of H (h2), A (h3) and a (h4). Usage: python3 make_cpp_widths.py > Pseudoscalar2HDMI_widths.h"""
import ast, os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "Pseudoscalar_2HDMI"))
import parameters as P
import decays as D

FUN = {"sqrt": "std::sqrt", "cos": "std::cos", "sin": "std::sin", "asin": "std::asin", "acos": "std::acos",
       "atan": "std::atan", "tan": "std::tan", "log": "std::log", "exp": "std::exp", "abs": "std::fabs"}

class CPP(ast.NodeVisitor):
    def visit_Expression(self, n): return self.visit(n.body)
    def visit_Constant(self, n): return repr(float(n.value))
    def visit_Name(self, n): return n.id
    def visit_Attribute(self, n):
        if n.attr == "pi": return "M_PI"
        raise ValueError(ast.dump(n))
    def visit_UnaryOp(self, n):
        return "(-%s)" % self.visit(n.operand) if isinstance(n.op, ast.USub) else self.visit(n.operand)
    def visit_BinOp(self, n):
        a, b = self.visit(n.left), self.visit(n.right)
        if isinstance(n.op, ast.Pow):
            if isinstance(n.right, ast.Constant) and float(n.right.value) == 2: return "sq(%s)" % a
            return "std::pow(%s,%s)" % (a, b)
        op = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*", ast.Div: "/"}[type(n.op)]
        return "(%s%s%s)" % (a, op, b)
    def visit_Call(self, n):
        f = n.func.attr if isinstance(n.func, ast.Attribute) else n.func.id
        return "%s(%s)" % (FUN[f], ", ".join(self.visit(x) for x in n.args))

def cpp(expr): return CPP().visit(ast.parse(expr.strip(), mode="eval"))

ext = [p for p in P.all_parameters if p.nature == "external"]
internal = [p for p in P.all_parameters if p.nature == "internal" and p.type == "real"]
want = {"h2": "H", "h3": "A", "h4": "a"}
o = []
w = o.append
w("// Generated by make_cpp_widths.py from the UFO model Pseudoscalar_2HDMI (parameters.py, decays.py).")
w("// Tree-level 2-body partial widths of H (h2), A (h3) and a (h4), as used by MadGraph. Do not edit by hand.")
w("#pragma once\n#include <cmath>\n#include <map>\n#include <string>\n#include <vector>\n")
w("namespace p2hdm {\ninline double sq(double x) { return x * x; }\n")
w("// a 2-body channel: |PDG ids| of the daughters and their nominal masses")
w("struct Chan { int id1, id2; double m1, m2; const char* name; };\n")
w("struct Model {")
w("  // ---- inputs (param_card), defaults = UFO defaults ----")
for p in ext:
    if p.name in ("MU_R",): continue
    w("  double %s = %s;  // %s %s" % (p.name, repr(float(p.value)), p.lhablock, p.lhacode))
w("  // ---- derived ----")
w("  double " + ", ".join(p.name for p in internal) + ";")
w("  void compute() {")
for p in internal:
    w("    %s = %s;" % (p.name, cpp(p.value)))
w("  }")
w("  // partial widths [GeV]; channels closed kinematically are skipped")
for dec in D.all_decays:
    if dec.particle.name not in want: continue
    w("  std::map<std::string, double> widths_%s() const {" % want[dec.particle.name])
    w("    std::map<std::string, double> w;")
    w("    const double m0 = %s;" % dec.particle.mass.name)
    for parts, expr in dec.partial_widths.items():
        masses = " + ".join(("0." if p.mass.name == "ZERO" else p.mass.name) for p in parts)
        key = " ".join(p.name for p in parts)
        w("    if (m0 > %s) w[\"%s\"] = %s;" % (masses, key, cpp(expr)))
    w("    return w;\n  }")
# channels with explicit daughter masses MOFF1, MOFF2 (needed for the off-shell / 3-body widths). The substitution
# is the one of scan2hdma.py (_daughter_fn): for identical daughters the Kallen function replaces
# sqrt(M^4 - 4 M^2 m^2) and m -> (MOFF1 + MOFF2)/2.
def moff_expr(expr, M, prods):
    n1, n2 = prods[0].mass.name, prods[1].mass.name
    lam = "cmath.sqrt(%s**4 + MOFF1**4 + MOFF2**4 - 2*%s**2*MOFF1**2 - 2*%s**2*MOFF2**2 - 2*MOFF1**2*MOFF2**2)" % (M, M, M)
    e = expr
    if n1 == n2:
        e = e.replace("cmath.sqrt(%s**4 - 4*%s**2*%s**2)" % (M, M, n1), lam)
        e = re.sub(r"\b%s\b" % n1, "(0.5*(MOFF1+MOFF2))", e)
    else:
        e = re.sub(r"\b%s\b" % n1, "MOFF1", e)
        e = re.sub(r"\b%s\b" % n2, "MOFF2", e)
    return e

offwant = {"h4": "a", "h2": "H", "h3": "A"}
for dec in D.all_decays:
    if dec.particle.name not in offwant: continue
    tag = offwant[dec.particle.name]
    M = dec.particle.mass.name
    items = list(dec.partial_widths.items())
    w("  // all channels of %s (closed ones included), widths with explicit daughter masses" % tag)
    w("  std::vector<Chan> chans_%s() const {" % tag)
    w("    return {")
    for parts, expr in items:
        ms = ["0." if p.mass.name == "ZERO" else p.mass.name for p in parts]
        w("      {%d, %d, %s, %s, \"%s\"}," % (abs(parts[0].pdg_code), abs(parts[1].pdg_code), ms[0], ms[1],
                                            " ".join(p.name for p in parts)))
    w("    };\n  }")
    w("  double pw_%s(int k, double MOFF1, double MOFF2) const {" % tag)
    w("    switch (k) {")
    for k, (parts, expr) in enumerate(items):
        w("      case %d: return %s;" % (k, cpp(moff_expr(expr, M, parts))))
    w("    }\n    return 0.;\n  }")
w("};\n")
w("inline double total(const std::map<std::string, double>& w) { double s = 0; for (auto& x : w) s += x.second; return s; }")
w("}  // namespace p2hdm")
print("\n".join(o))
